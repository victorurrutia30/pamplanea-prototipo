import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { abrir, esperar } from './cdp.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = Object.fromEntries(process.argv.slice(3).map((a) => a.replace(/^--/, '').split('=')));
const ronda = process.argv[2] || '1';
const base = args.base || pathToFileURL(root).href + '/';
const tema = args.tema || 'serena-claro';
const salida = path.join(root, 'capturas', `ux-${ronda}${args.base ? '-servida' : ''}`, tema);
await mkdir(salida, { recursive: true });
const b = await abrir({ puerto: Number(args.puerto || 9811) });
await b.tamano(390, 844);
await b.movimientoReducido(true);
const js = (s) => JSON.stringify(s);
const ev = (s) => b.evaluar(s);
let n = 0;
const foto = async (nombre) => {
    await esperar(160);
    await b.captura(path.join(salida, `${String(++n).padStart(2, '0')}-${nombre}.png`));
};
const clic = async (sel) => {
    const ok = await ev(`(() => { const el = document.querySelector(${js(sel)}); if (!el) return false; el.scrollIntoView({ block: 'center' }); el.click(); return true; })()`);
    if (!ok) console.error('no encontré ' + sel);
    await esperar(100);
};
const caso = async (hash) => {
    await b.ir('about:blank');
    await b.ir(base + 'telefono.html#' + hash + '&tema=' + tema);
    await esperar(350);
};
const abajo = async (y) => {
    await ev(`document.getElementById('vista').scrollTop = ${y}; document.querySelector('.hoja-c') && (document.querySelector('.hoja-c').scrollTop = ${y}); true`);
};

